//! Actions and key bindings.

use gpui::{actions, App, KeyBinding};

actions!(
    nota,
    [
        Backspace,
        Delete,
        Left,
        Right,
        Up,
        Down,
        SelectLeft,
        SelectRight,
        SelectUp,
        SelectDown,
        WordLeft,
        WordRight,
        SelectWordLeft,
        SelectWordRight,
        LineStart,
        LineEnd,
        SelectLineStart,
        SelectLineEnd,
        DocStart,
        DocEnd,
        DeleteWordLeft,
        DeleteToLineStart,
        SelectAll,
        Copy,
        Cut,
        Paste,
        Enter,
        ShiftEnter,
        Escape,
        Tab,
        ShiftTab,
        Undo,
        Redo,
        Bold,
        Italic,
        Underline,
        Strike,
        InlineCode,
        MoveBlockUp,
        MoveBlockDown,
        DuplicateBlock,
        TurnText,
        TurnH1,
        TurnH2,
        TurnH3,
        TurnTodo,
        TurnBullet,
        TurnNumbered,
        TurnToggle,
        TurnCode,
        Quit,
        CheckForUpdates,
        NewPage,
        ToggleSidebar,
        ToggleAi,
        QuickFind,
        InsertLink,
        ToggleTheme,
        GoBack,
        GoForward,
    ]
);

const TEXT: Option<&str> = Some("TextInput || Editor");
const EDITOR: Option<&str> = Some("Editor");

pub fn bind_keys(cx: &mut App) {
    let mut keys = vec![
        KeyBinding::new("backspace", Backspace, TEXT),
        KeyBinding::new("shift-backspace", Backspace, TEXT),
        KeyBinding::new("delete", Delete, TEXT),
        KeyBinding::new("left", Left, TEXT),
        KeyBinding::new("right", Right, TEXT),
        KeyBinding::new("up", Up, TEXT),
        KeyBinding::new("down", Down, TEXT),
        KeyBinding::new("shift-left", SelectLeft, TEXT),
        KeyBinding::new("shift-right", SelectRight, TEXT),
        KeyBinding::new("shift-up", SelectUp, TEXT),
        KeyBinding::new("shift-down", SelectDown, TEXT),
        KeyBinding::new("home", LineStart, TEXT),
        KeyBinding::new("end", LineEnd, TEXT),
        KeyBinding::new("shift-home", SelectLineStart, TEXT),
        KeyBinding::new("shift-end", SelectLineEnd, TEXT),
        KeyBinding::new("enter", Enter, TEXT),
        KeyBinding::new("shift-enter", ShiftEnter, TEXT),
        KeyBinding::new("escape", Escape, TEXT),
        KeyBinding::new("tab", Tab, TEXT),
        KeyBinding::new("shift-tab", ShiftTab, TEXT),
        KeyBinding::new("secondary-a", SelectAll, TEXT),
        KeyBinding::new("secondary-c", Copy, TEXT),
        KeyBinding::new("secondary-x", Cut, TEXT),
        KeyBinding::new("secondary-v", Paste, TEXT),
        KeyBinding::new("secondary-z", Undo, TEXT),
        KeyBinding::new("secondary-shift-z", Redo, TEXT),
        KeyBinding::new("secondary-b", Bold, EDITOR),
        KeyBinding::new("secondary-i", Italic, EDITOR),
        KeyBinding::new("secondary-u", Underline, EDITOR),
        KeyBinding::new("secondary-shift-s", Strike, EDITOR),
        KeyBinding::new("secondary-e", InlineCode, EDITOR),
        KeyBinding::new("secondary-shift-up", MoveBlockUp, EDITOR),
        KeyBinding::new("secondary-shift-down", MoveBlockDown, EDITOR),
        KeyBinding::new("secondary-d", DuplicateBlock, EDITOR),
        KeyBinding::new("secondary-alt-0", TurnText, EDITOR),
        KeyBinding::new("secondary-alt-1", TurnH1, EDITOR),
        KeyBinding::new("secondary-alt-2", TurnH2, EDITOR),
        KeyBinding::new("secondary-alt-3", TurnH3, EDITOR),
        KeyBinding::new("secondary-alt-4", TurnTodo, EDITOR),
        KeyBinding::new("secondary-alt-5", TurnBullet, EDITOR),
        KeyBinding::new("secondary-alt-6", TurnNumbered, EDITOR),
        KeyBinding::new("secondary-alt-7", TurnToggle, EDITOR),
        KeyBinding::new("secondary-alt-8", TurnCode, EDITOR),
        // global
        KeyBinding::new("secondary-n", NewPage, None),
        KeyBinding::new("secondary-\\", ToggleSidebar, None),
        KeyBinding::new("secondary-j", ToggleAi, None),
        KeyBinding::new("secondary-p", QuickFind, None),
        KeyBinding::new("secondary-k", QuickFind, None),
        // with text selected in a page, ⌘K makes a link (like Notion)
        KeyBinding::new("secondary-k", InsertLink, EDITOR),
        KeyBinding::new("secondary-shift-l", ToggleTheme, None),
        KeyBinding::new("secondary-[", GoBack, None),
        KeyBinding::new("secondary-]", GoForward, None),
        KeyBinding::new("secondary-q", Quit, None),
    ];
    if cfg!(target_os = "macos") {
        keys.extend([
            KeyBinding::new("alt-left", WordLeft, TEXT),
            KeyBinding::new("alt-right", WordRight, TEXT),
            KeyBinding::new("alt-shift-left", SelectWordLeft, TEXT),
            KeyBinding::new("alt-shift-right", SelectWordRight, TEXT),
            KeyBinding::new("cmd-left", LineStart, TEXT),
            KeyBinding::new("cmd-right", LineEnd, TEXT),
            KeyBinding::new("cmd-shift-left", SelectLineStart, TEXT),
            KeyBinding::new("cmd-shift-right", SelectLineEnd, TEXT),
            KeyBinding::new("cmd-up", DocStart, TEXT),
            KeyBinding::new("cmd-down", DocEnd, TEXT),
            KeyBinding::new("alt-backspace", DeleteWordLeft, TEXT),
            KeyBinding::new("cmd-backspace", DeleteToLineStart, TEXT),
            KeyBinding::new("ctrl-a", LineStart, TEXT),
            KeyBinding::new("ctrl-e", LineEnd, TEXT),
        ]);
    } else {
        keys.extend([
            KeyBinding::new("ctrl-left", WordLeft, TEXT),
            KeyBinding::new("ctrl-right", WordRight, TEXT),
            KeyBinding::new("ctrl-shift-left", SelectWordLeft, TEXT),
            KeyBinding::new("ctrl-shift-right", SelectWordRight, TEXT),
            KeyBinding::new("ctrl-home", DocStart, TEXT),
            KeyBinding::new("ctrl-end", DocEnd, TEXT),
            KeyBinding::new("ctrl-backspace", DeleteWordLeft, TEXT),
            KeyBinding::new("ctrl-y", Redo, TEXT),
        ]);
    }
    cx.bind_keys(keys);
}
